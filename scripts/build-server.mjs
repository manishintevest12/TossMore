// Bundles the Express + WebSocket server (server.ts -> server.js) so hosts that
// run a plain Node entry file (Hostinger, Passenger, PM2, `node server.js`) can
// start the backend without a TypeScript loader.
//
// Usage: node scripts/build-server.mjs
//
// server.js is committed to the repo, so if esbuild is unavailable (for example
// a host that installs production dependencies only) the build keeps the last
// committed bundle instead of failing the whole deploy.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const outfile = path.join(root, 'server.js');

let esbuild;
try {
  esbuild = await import('esbuild');
} catch {
  esbuild = null;
}

if (!esbuild) {
  if (fs.existsSync(outfile)) {
    console.warn(
      '[build-server] esbuild is not installed; keeping the committed server.js. Install dev dependencies to rebuild it.',
    );
    process.exit(0);
  }
  console.error('[build-server] esbuild is not installed and no server.js exists. Run "npm install" first.');
  process.exit(1);
}

await esbuild.build({
  entryPoints: [path.join(root, 'server.ts')],
  outfile,
  bundle: true,
  platform: 'node',
  format: 'esm',
  target: 'node20',
  // Keep npm packages external: they are installed from node_modules at runtime.
  packages: 'external',
  sourcemap: false,
  banner: {
    js: '// AUTO-GENERATED from server.ts by scripts/build-server.mjs — do not edit by hand.\n// Regenerated by `npm run build`.',
  },
  logLevel: 'info',
});

console.log('Built server.js — start it with: node server.js');
